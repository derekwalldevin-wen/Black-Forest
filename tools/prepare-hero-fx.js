async function characters(source,m){
 const data=await sharp(source).ensureAlpha().raw().toBuffer(),seen=new Uint8Array(m.width*m.height),parts=[];
 for(let p=0;p<seen.length;p++){
  if(seen[p]||data[p*4+3]<16)continue;const queue=[p];seen[p]=1;let n=0,l=m.width,t=m.height,r=-1,b=-1;
  for(let k=0;k<queue.length;k++){const v=queue[k],x=v%m.width,y=Math.floor(v/m.width);n++;l=Math.min(l,x);t=Math.min(t,y);r=Math.max(r,x);b=Math.max(b,y);for(const z of [v-1,v+1,v-m.width,v+m.width])if(z>=0&&z<seen.length&&!seen[z]&&Math.abs(z%m.width-x)<=1&&data[z*4+3]>=16){seen[z]=1;queue.push(z);}}
  if(n>20000)parts.push({left:l,top:t,right:r,bottom:b,n});
 }
 if(parts.length!==4)throw Error('Expected four isolated heroine silhouettes, got '+parts.length);
 parts.sort((a,b)=>Math.floor((a.top+a.bottom)/m.height)-Math.floor((b.top+b.bottom)/m.height)||a.left-b.left);
 const scale=272/Math.max(...parts.map(p=>Math.max(p.right-p.left+1,p.bottom-p.top+1))),layers=[],frames=[];
 for(let i=0;i<4;i++){
  const p=parts[i],l=Math.max(0,p.left-22),t=Math.max(0,p.top-22),r=Math.min(m.width,p.right+23),b=Math.min(m.height,p.bottom+23),w=r-l,h=b-t;
  const width=Math.round(w*scale),height=Math.round(h*scale),left=Math.round(160-((p.left+p.right)/2-l)*scale),top=Math.round(302-(p.bottom+1-t)*scale);
  if(left<0||top<0||left+width>320||top+height>320)throw Error('Hero crop would clip pose '+i);
  const input=await sharp(source).extract({left:l,top:t,width:w,height:h}).resize(width,height).png().toBuffer();layers.push({input,left:i%2*320+left,top:Math.floor(i/2)*320+top});
  frames.push({frame:i,sourceBounds:p,crop:{left:l,top:t,width:w,height:h},scale,anchorY:302});
 }
 return {layers,frames};
}
