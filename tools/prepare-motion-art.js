// Technical atlas preparation only: fixed cell extraction, common scale, ground alignment.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
let sharp;
try { sharp = require('sharp'); } catch { sharp = require('C:/Users/Administrator/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp'); }
const root = path.resolve(__dirname, '..');
const ids = ['wolf','mushroom','witch','boar','alpha-wolf','bog-witch','forest-lord','nine-tail','lu-shu','qiongqi','xiangliu','fei','huodou','taotie','baize','dijiang'];
function bounds(data, w, h) {
  let l=w, t=h, r=-1, b=-1, transparent=0;
  for(let y=0;y<h;y++) for(let x=0;x<w;x++) {
    const a=data[(y*w+x)*4+3]; if(a===0) transparent++;
    if(a>48) {l=Math.min(l,x);r=Math.max(r,x);t=Math.min(t,y);b=Math.max(b,y);}
  }
  if(r<0 || transparent/(w*h)<.05) throw Error('Empty frame or missing transparent background');
  return {left:l,top:t,width:r-l+1,height:b-t+1,bottom:b,transparent:transparent/(w*h)};
}
(async()=>{
  fs.mkdirSync(path.join(root,'assets/anim'),{recursive:true});
  const manifest={enemies:{},effects:{}}, report=[];
  for(const id of ids) {
    const source=path.join(root,'docs/art/motion/source',id+'-poses.png');
    const meta=await sharp(source).metadata();
    if(meta.width!==1536 || meta.height!==1024 || !meta.hasAlpha) throw Error(id+': expected 1536x1024 RGBA');
    const frames=[];
    for(let i=0;i<6;i++) {
      const {data,info}=await sharp(source).extract({left:(i%3)*512,top:Math.floor(i/3)*512,width:512,height:512}).ensureAlpha().raw().toBuffer({resolveWithObject:true});
      frames.push({data,info,b:bounds(data,512,512)});
    }
    // One scale for the entire character; never fit each pose separately.
    const scale=Math.min(.70,350/Math.max(...frames.map(f=>Math.max(f.b.width,f.b.height))));
    const drawSize=Math.round(512*scale), cell=416, anchorY=384;
    const layers=[];
    const neutralCenter=frames[0].b.left+frames[0].b.width/2;
    for(let i=0;i<6;i++) {
      const f=frames[i];
      const left=Math.round(cell/2-neutralCenter*scale);
      const top=Math.round(anchorY-(f.b.bottom+1)*scale);
      if (left+f.b.left*scale<0 || left+(f.b.left+f.b.width)*scale>cell ||
          top+f.b.top*scale<0 || top+(f.b.bottom+1)*scale>cell) throw Error(id+': foreground would be clipped');
      if(left<0 || top<0 || left+drawSize>cell || top+drawSize>cell) {
        // Crop only transparent padding to fit the canvas; keep all foreground pixels.
        const resized=await sharp(f.data,{raw:f.info}).resize(drawSize,drawSize).png().toBuffer();
        const cutL=Math.max(0,-left),cutT=Math.max(0,-top);
        const width=Math.min(drawSize-cutL,cell-Math.max(0,left)),height=Math.min(drawSize-cutT,cell-Math.max(0,top));
        const input=await sharp(resized).extract({left:cutL,top:cutT,width,height}).png().toBuffer();
        layers.push({input,left:(i%3)*cell+Math.max(0,left),top:Math.floor(i/3)*cell+Math.max(0,top)});
      } else {
        const input=await sharp(f.data,{raw:f.info}).resize(drawSize,drawSize).png().toBuffer();
        layers.push({input,left:(i%3)*cell+left,top:Math.floor(i/3)*cell+top});
      }
    }
    const file='assets/anim/enemy-'+id+'.png';
    await sharp({create:{width:cell*3,height:cell*2,channels:4,background:'#00000000'}}).composite(layers).png().toFile(path.join(root,file));
    manifest.enemies['enemy-'+id]={key:'motion-'+id,file,frameWidth:cell,frameHeight:cell,anchorY,visibleHeight:Math.round(frames[0].b.height*scale)};
    report.push({id,sourceHash:crypto.createHash('sha256').update(fs.readFileSync(source)).digest('hex'),frames:frames.map(f=>f.b),scale,bytes:fs.statSync(path.join(root,file)).size});
  }
  for(const id of ['claw-impact','shield-impact','heal']) {
    const source=path.join(root,'docs/art/motion/source',id+'.png');
    const meta=await sharp(source).metadata();
    if(meta.width!==1536 || meta.height!==1024 || !meta.hasAlpha) throw Error(id+': wrong atlas');
    const file='assets/anim/fx-'+id+'.png';
    await sharp(source).resize(768,512).png().toFile(path.join(root,file));
    manifest.effects[id]={key:'motion-fx-'+id,file,frameWidth:256,frameHeight:256};
  }
  fs.writeFileSync(path.join(root,'src/core/motion-assets.js'),'// Generated by tools/prepare-motion-art.js\nconst MOTION_ASSETS = '+JSON.stringify(manifest,null,2)+';\n');
  fs.writeFileSync(path.join(root,'docs/art/motion/ASSET-REPORT.json'),JSON.stringify(report,null,2)+'\n');
  console.log('Prepared 16 enemy atlases (96 poses), 3 FX atlases (18 frames).');
})().catch(e=>{console.error(e);process.exitCode=1;});
